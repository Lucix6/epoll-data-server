// 🎯 核心设计思想
// 1. I/O与计算分离的多线程架构

// 主线程只负责网络I/O：使用epoll的I/O多路复用技术，同时处理数千个客户端连接
// 工作线程池负责数据处理：协议解析、订阅管理、数据转发都在工作线程中执行
// 主线程永远不会被阻塞，能够持续接收新的连接和数据
// 2. 生产者-消费者模型实现线程通信

// 主线程是生产者：收到数据后封装成任务推入队列
// 工作线程是消费者：从队列中取出任务进行处理
// 使用条件变量实现阻塞等待，避免忙轮询节省CPU
// 3. 发布-订阅模式实现视频流分发

// 客户端可以发送TYPE_SUBSCRIBE(0xFE)消息订阅自己感兴趣的数据流类型
// 任何客户端发送的数据流，都会被服务器转发给所有订阅了该类型的客户端
// 完美支持一对多的视频直播场景：一个摄像头推流，多个观众同时收看
// 📦 协议格式详解
// 每个帧的格式为：


// plainText
// [1字节类型][4字节数据长度(网络字节序)][N字节数据]
//   └───────┘ └───────────────────────┘ └──────┘
//      5字节协议头部                       数据内容
// 类型0xFE：订阅消息，数据部分是要订阅的数据流类型列表（每个类型1字节）
// 类型0x00~0xFD：普通数据流，服务器会转发给所有订阅者
// 🔒 线程安全设计
// 所有共享数据结构都配有互斥锁保护
// 任务队列、订阅表、解析器数组都能安全地在多线程环境下访问
// 条件变量实现生产者消费者的同步
// 📡 视频流分发流程示例
// 观众客户端A连接服务器，发送订阅消息[0xFE][0x00000001][0x01]，订阅类型1的数据流
// 主播客户端B连接服务器，发送视频帧数据[0x01][视频长度][H.264视频数据]
// 主线程收到B的数据，推入任务队列
// 某个工作线程取出任务，解析出完整帧，发现是类型1的数据
// 查询订阅表，获取所有订阅类型1的客户端列表（包含A）
// 工作线程将该视频帧重新组帧，发送给客户端A
// 多个观众都能同时收到主播的视频流，实现直播分发
