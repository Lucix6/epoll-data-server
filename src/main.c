/**
 * @file main.c
 * @brief epoll多线程视频流分发服务器的主入口文件
 * @details 实现了服务器的初始化、组件启动、信号处理和优雅退出
 */
#include "common.h"      // 通用常量定义
#include "queue.h"       // 任务队列（线程间通信）
#include "subscription.h"// 订阅管理模块
#include "worker.h"      // 工作线程池
#include "epoll_loop.h"  // epoll事件循环模块
#include <signal.h>      // 信号处理
#include <stdio.h>
#include <stdlib.h>

/** 服务器运行标志，volatile确保多线程间可见性 */
static volatile int keep_running = 1;

/**
 * @brief SIGINT信号处理函数（Ctrl+C捕获）
 * @param sig 信号编号
 * @details 负责优雅关闭服务器，停止所有组件
 */
void handle_sigint(int sig) {
    keep_running = 0;
    stop_epoll_loop();   // 停止epoll事件循环
    stop_workers();      // 停止所有工作线程
}

/**
 * @brief 主函数
 * @return 程序退出码
 * @details 初始化所有模块，启动服务器，等待退出信号后清理资源
 */
int main() {
    queue_init();           // 初始化任务队列（主线程与工作线程通信）
    subscription_init();    // 初始化订阅管理模块
    start_workers();        // 启动工作线程池
    signal(SIGINT, handle_sigint);  // 注册Ctrl+C信号处理
    start_epoll_loop();     // 启动epoll事件循环，开始接受连接和处理事件
    
    // 服务器退出后清理资源
    queue_destroy();
    subscription_destroy();
    printf("服务器退出\n");
    return 0;
}

